export let lang = (() => {
  try {
    const s = localStorage.getItem('bp2-lang'); if (s) return s;
    const st = JSON.parse(localStorage.getItem('bric-masasi-v2') || 'null'), L = st && st.SET && st.SET.lang;   // the first BridgePlay's choice
    if (L && (D[L] || L === 'en')) return L;
  } catch (e) {}
  const n = String(navigator.language || 'en').slice(0, 2).toLowerCase().replace(/^n[bn]$/, 'no');
  return D[n] ? n : 'en';
})();
export function setLang(l) { lang = l; try { localStorage.setItem('bp2-lang', l); } catch (e) {} document.documentElement.lang = l === 'no' ? 'nb' : l; }
